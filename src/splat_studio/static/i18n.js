  function getLang() {
    let saved = null;
    try { saved = localStorage.getItem("lang"); } catch (e) { /* storage blocked */ }
    if (saved && I18N[saved]) return saved;
    const nav = (navigator.language || "en").toLowerCase();
    return nav.startsWith("pt") ? "pt" : "en";
  }

  let lang = getLang();

  function t(key, params) {
    let s = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key];
    if (s === undefined) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
    return s;
  }

  function has(key) { return I18N.en[key] !== undefined; }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    for (const attr of ["placeholder", "title", "aria-label"]) {
      const data = "i18n" + attr.replace(/(^|-)(\w)/g, (m, d, c) => c.toUpperCase());
      root.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => el.setAttribute(attr, t(el.dataset[data])));
    }
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  }

  function setLang(next) {
    if (!I18N[next]) return;
    lang = next;
    try { localStorage.setItem("lang", next); } catch (e) { /* storage blocked */ }
    apply();
    window.dispatchEvent(new CustomEvent("langchange", { detail: next }));
  }

  // A <select> language switcher, placed wherever <span data-lang-switcher> is.
  function mountSwitcher() {
    document.querySelectorAll("[data-lang-switcher]").forEach((host) => {
      const sel = document.createElement("select");
      sel.className = "lang-select";
      sel.setAttribute("data-testid", "lang-select");
      sel.setAttribute("aria-label", t("lang.label"));
      for (const [code, name] of Object.entries(LANGS)) {
        const o = document.createElement("option");
        o.value = code; o.textContent = name; o.selected = code === lang;
        sel.appendChild(o);
      }
      sel.addEventListener("change", () => setLang(sel.value));
      host.replaceChildren(sel);
    });
  }

  window.I18N = I18N;
  window.i18n = { t, has, apply, setLang, getLang: () => lang, languages: LANGS, mountSwitcher };
  window.t = t;
